// Embeds logos/<id>.svg into src/logos.generated.ts. Run `pnpm logos` after
// adding or changing a logo; test/logos.test.ts fails while the two differ.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export function renderLogos(dir = join(root, 'logos')) {
  const entries = readdirSync(dir)
    .filter((file) => file.endsWith('.svg'))
    .sort()
    .map((file) => {
      const svg = readFileSync(join(dir, file), 'utf8')
        .replace(/<\?xml[^>]*\?>/g, '')
        .replace(/<!--[\s\S]*?-->/g, '')
        .replace(/>\s+</g, '><')
        .trim()
      return `  ${JSON.stringify(file.slice(0, -4))}: ${JSON.stringify(svg)}`
    })
  return `// Generated by scripts/build-logos.mjs from logos/*.svg. Do not edit; run \`pnpm logos\`.\nexport const LOGOS: Record<string, string> = {\n${entries.join(',\n')}\n}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'src', 'logos.generated.ts'), renderLogos())
}
